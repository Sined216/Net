"""Оптимистичная блокировка: кто сохранил вторым, тот узнаёт об этом.

За одной базой сидят несколько человек. Двое открыли одну и ту же железку,
первый поправил расположение, второй — заметку; второй сохраняет и молча
затирает правку первого своим снимком формы. Заметить такое нельзя: в
журнале обе правки на месте, а в базе — только вторая.

Лечится номером правки. У записи есть `version`; клиент присылает тот, что
видел на экране, и если он разошёлся с текущим — значит кто-то успел
раньше. Тогда сохранение отбивается 409, а человек обновляет страницу и
решает сам. Блокировок нет, слияния изменений нет: для системы, где
одновременная правка одной железки — редкость, а не режим работы, этого
достаточно.

Номер не трогают действия, которые правкой записи не являются:
перетаскивание узла по схеме меняет только координаты, и мешать из-за него
чужому сохранению незачем.
"""

from fastapi import HTTPException

CONFLICT_MESSAGE = (
    "Запись изменена другим пользователем — обновите страницу, "
    "чтобы не затереть его правку"
)


def check(entity, expected: int | None) -> None:
    """Сверить номер правки. `None` — клиент старый или это не правка формы:
    тогда проверять нечего, поведение остаётся прежним."""
    if expected is None:
        return
    if expected != (entity.version or 1):
        raise HTTPException(status_code=409, detail=CONFLICT_MESSAGE)


def bump(entity) -> None:
    """Записали — номер вырос."""
    entity.version = (entity.version or 1) + 1


def differs(entity, data: dict) -> bool:
    """Правка что-то меняет или это сохранение без изменений?

    Форма отправляет все свои поля целиком, поэтому «сохранил, ничего не
    поправив» — обычное дело. Двигать номер на такое нельзя: у соседа,
    который в это время правит ту же запись, сохранение отбилось бы без
    всякой причины.
    """
    return any(getattr(entity, field) != value for field, value in data.items())
