import { createTheme, type MantineColorsTuple } from '@mantine/core';

/** Тема интерфейса.
 *
 * Заведена ради одной вещи — тёмного фона. Палитра Mantine по умолчанию
 * даёт под тёмную тему нейтрально-серый `#242424`: это не чёрный, а серый,
 * и на весь экран он читается как задымление. Глаза от него устают быстрее,
 * чем от настоящего тёмного фона: контраст текста к нему ниже, а само
 * полотно при этом само по себе светится.
 *
 * Здесь фон опущен почти до чёрного, а разница между фоном страницы и
 * поверхностями (карточки, поля, врезки) оставлена заметной — иначе
 * «почти чёрный на почти чёрном» превращается в кашу, где не видно границ
 * блоков. Оттенок уведён в холод на пару единиц: на этой глубине это не
 * читается как синева, но убирает грязноватый бурый привкус, который дают
 * строго нейтральные серые.
 */

/** Ступени, которые Mantine разбирает по смыслу (см. resolver темы):
 * 0 — текст, 2 — приглушённый текст, 3 — подсказка в пустом поле,
 * 4 — границы, 5 — наведение, 6 — поверхность (карточки, поля),
 * 7 — фон страницы. Восьмая и девятая нужны компонентам, которые уходят
 * ещё глубже фона, — например всплывающим подложкам. */
const dark: MantineColorsTuple = [
  '#c9ccd1',
  '#b2b6bd',
  '#8b9098',
  '#6b7078',
  '#33363c',
  '#25282d',
  '#191b1f',
  '#0e1013',
  '#090a0c',
  '#050607',
];

export const theme = createTheme({
  colors: { dark },
});

/** Фон схемы и структуры базы. Полотно — это тот же фон страницы, и
 * задавать его вторым набором значений (как было раньше, ещё от шестой
 * версии Mantine) значит гарантированно разойтись с темой при первом же
 * обновлении библиотеки: так и вышло — полотно осталось на `#1a1b1e`, пока
 * страница уехала на `#242424`, и стык был виден глазом. Теперь значения
 * берутся отсюда, из одного места с палитрой выше. */
export const CANVAS = {
  /** Фон полотна — ровно фон страницы, стыка быть не должно. */
  background: dark[7],
  /** Поверхность поверх полотна: врезки подписей, кнопки панелей. */
  surface: dark[6],
  /** Карточка узла на схеме связей — на ступень светлее поверхности,
   * иначе на почти чёрном фоне у неё пропадает объём. */
  card: '#1e2126',
  border: dark[4],
} as const;
